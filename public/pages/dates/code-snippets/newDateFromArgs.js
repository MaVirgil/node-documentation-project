// with year and month
console.log(new Date(2025, 0).toString());
// => Wed Jan 01 2025 00:00:00 GMT+0100 (Central European Standard Time)

//with year, month and day
console.log(new Date(2025, 0, 5).toString());
// => Sun Jan 05 2025 00:00:00 GMT+0100 (Central European Standard Time)

// with year, month, day, hour, minute and second
console.log(new Date(2025, 0, 5, 13, 48, 59).toString());
// => Sun Jan 05 2025 13:48:59:300 GMT+0100 (Central European Standard Time)